#!/bin/sh
# One command: read the three guards from the code, write the TLC config, run TLC.
#   .claude/skills/formal-onboarding-finish-flow/run.sh [OUT_DIR]
# Needs Java 11+ and TLC 1.7.4: set TLA2TOOLS to tla2tools.jar (JAVA optional),
# or have a `tlc` command on PATH.
# Exit 0: every rule holds. Exit 12: a rule breaks (see OUT_DIR/tlc.out). Other: setup error.
set -eu

here=$(cd "$(dirname "$0")" && pwd)
repo=$(cd "$here/../../.." && pwd)
out=${1:-"${TMPDIR:-/tmp}/formal-onboarding-finish-flow"}
mkdir -p "$out"

model="$repo/Purrtine/Models/OnboardingTaskSetupModel.swift"
builder="$repo/Purrtine/Utilities/OnboardingDataBuilder.swift"
app="$repo/Purrtine/PurrtineApp.swift"
manager="$repo/Purrtine/Utilities/OnboardingManager.swift"
for f in "$model" "$builder" "$app" "$manager"; do
  [ -f "$f" ] || { echo "missing $f: the covered code moved, update the skill" >&2; exit 2; }
done

# anchor FILE TEXT -> TRUE when TEXT (fixed string, whitespace-trimmed lines) is in FILE.
anchor() {
  if sed 's/^[[:space:]]*//' "$1" | grep -qF -- "$2"; then echo TRUE; else echo FALSE; fi
}

# FinishGuard: the double-tap guard at the top of finish().
finish_guard=$(anchor "$model" 'guard isFinishing == false else { return .alreadyFinishing }')

# UnstageOnFail: both failed-first-commit paths take the cat back out of the context.
u1=$(anchor "$builder" 'unstage(cat, [], photoPath: photoPath, in: modelContext)')
u2=$(anchor "$builder" 'unstage(cat, tasks, photoPath: photoPath, in: modelContext)')
if [ "$u1" = TRUE ] && [ "$u2" = TRUE ]; then unstage=TRUE; else unstage=FALSE; fi

# FlagOnlyAfterSave: finish() calls completeOnboarding only in the branch after `.notSaved`.
flag_only=FALSE
if awk '
  /func finish\(\) async -> FinishOutcome/ { infn = 1 }
  infn && /if outcome == \.notSaved \{/ { seen_if = 1 }
  infn && seen_if && /isShowingSaveFailure = true/ { seen_alert = 1 }
  infn && seen_alert && /\} else \{/ { seen_else = 1 }
  infn && /completeOnboarding\(\)/ { if (seen_else) ok = 1; else bad = 1 }
  infn && /^    \}$/ { infn = 0 }
  END { exit (ok && !bad) ? 0 : 1 }
' "$model"; then flag_only=TRUE; fi

# LaunchRepair: at launch, a store that holds a cat sets hasCompletedOnboarding (#140).
r1=$(anchor "$app" 'OnboardingManager.shared.completeIfStoreHoldsCat(in: container.mainContext)')
r2=$(anchor "$manager" 'let catCount = try context.fetchCount(FetchDescriptor<Cat>())')
r3=$(anchor "$manager" 'if catCount > 0 {')
if [ "$r1" = TRUE ] && [ "$r2" = TRUE ] && [ "$r3" = TRUE ]; then launch_repair=TRUE; else launch_repair=FALSE; fi

echo "Guards read from the code:"
echo "  FinishGuard       = $finish_guard  (double-tap guard in finish())"
echo "  UnstageOnFail     = $unstage  (failed first commit unstages the cat)"
echo "  FlagOnlyAfterSave = $flag_only  (hasCompletedOnboarding only after a save)"
echo "  LaunchRepair      = $launch_repair  (a saved cat completes onboarding at launch)"

cp "$here/OnboardingFinish.tla" "$here/view.mjs" "$out/"
cat > "$out/OnboardingFinish.cfg" <<EOF
\\* Generated by run.sh from the code at $(git -C "$repo" rev-parse --short HEAD 2>/dev/null || echo unknown)
SPECIFICATION Spec
CONSTANTS
  FinishGuard = $finish_guard
  UnstageOnFail = $unstage
  FlagOnlyAfterSave = $flag_only
  LaunchRepair = $launch_repair
CONSTRAINT Bound
VIEW FlowView
INVARIANTS
  TypeOK
  OneFirstCat
  HomeHasCatUnlessChosen
  NoSavedCatBehindOnboarding
EOF

if [ -n "${TLA2TOOLS:-}" ]; then
  set -- "${JAVA:-java}" -XX:+UseParallelGC -cp "$TLA2TOOLS" tlc2.TLC
elif command -v tlc >/dev/null 2>&1; then
  set -- tlc
else
  echo "TLC not found: set TLA2TOOLS to tla2tools.jar (v1.7.4)." >&2
  exit 2
fi

cd "$out"
status=0
"$@" -workers 1 -continue -config OnboardingFinish.cfg OnboardingFinish.tla > tlc.out 2>&1 || status=$?
grep -E "^Error: Invariant .* is violated|distinct states found" tlc.out | sort -u || true
broken=$(grep -c "^Error: Invariant .* is violated" tlc.out || true)
if [ "$broken" -gt 0 ]; then
  echo "RULES BROKEN: see $out/tlc.out; read it with /statechart (spec, cfg and view are in $out)"
  exit 12
fi
[ "$status" -eq 0 ] || { echo "TLC stopped with status $status: see $out/tlc.out" >&2; exit "$status"; }
echo "ALL RULES HOLD (spec, cfg and view are in $out)"
